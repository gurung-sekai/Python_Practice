# You can add a new key-value pair to a dictionary by assigning a value to a new key, like oscar_winners["Supporting Actress"] = "Viola Davis".
# You can change the value of an existing key by assigning a new value to that key, like oscar_winners["Best Picture"] = "Moonlight".
# The lesson teaches how to both add and overwrite values in a dictionary.

oscar_winners = {"Best Picture": "La La Land", "Best Actor": "Casey Affleck", "Best Actress": "Emma Stone", "Animated Feature": "Zootopia"}

oscar_winners["Supporting Actress"] = "Viola Davis"
oscar_winners["Best Picture"] = "Moonlight"
